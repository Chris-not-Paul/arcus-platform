function findGroup(eventId) {
  return PIEMONTE_2000_GROUPS.find((group) => group.ids.includes(eventId));
}

function curatedSources(existingSources) {
  return [
    PIEMONTE_2000_REPORT,
    ...existingSources.filter(
      (source) => source.source_id !== PIEMONTE_2000_REPORT.source_id
    ),
  ];
}

function sourcesWith(primarySource, existingSources) {
  return [
    primarySource,
    ...existingSources.filter((source) => source.source_id !== primarySource.source_id),
  ];
}

function applyAdditionalCuration(context, curation) {
  const primarySource = curation.source ?? context.sources[0];
  if (!primarySource) return null;

  const common = {
    ...context,
    status: "context_available",
    display_badge: primarySource.provider,
    sources: curation.replace_sources
      ? [primarySource]
      : sourcesWith(primarySource, context.sources),
    provenance: {
      method: "Manual extraction encoded in the ARCUS event-report curation registry",
      source_registry_accessed_through: primarySource.accessed_at,
    },
  };
  delete common.review;

  if (curation.type === "gap") {
    return {
      ...common,
      coverage_level: "validated_event_report_review",
      event_hydrometry: {
        observation_status: "not_available",
        reason_code: curation.reason_code,
        observed_discharge_m3s: null,
        observed_stage_m: null,
        hydrograph: null,
        network_status: {
          network: primarySource.title,
          summary_it: curation.summary_it,
          summary_en: curation.summary_en,
        },
      },
      reference_station: null,
      curation_note: { it: curation.summary_it, en: curation.summary_en },
      caveats: [
        "The cited source review is complete; no compatible tabulated bridge-section value is assigned.",
        "ARCUS does not digitise plotted hydrographs into false-precision event peaks.",
        "The encoded failure process remains separate from hydrometric evidence.",
        "Rainfall is not converted into stage or discharge.",
      ],
    };
  }

  return {
    ...common,
    coverage_level: curation.coverage_level,
    event_hydrometry: {
      observation_status: curation.observation_status,
      interpretation: curation.interpretation,
      observed_discharge_m3s: null,
      observed_stage_m: null,
      hydrograph: null,
      observations: curation.observations,
    },
    reference_station: curation.station,
    curation_note: { it: curation.note_it, en: curation.note_en },
    caveats: [
      "The value describes the named official station and is not assigned to the collapsed bridge section.",
      "Sensor readings and post-event topographic surveys retain their distinct evidence types.",
      "The encoded failure process remains separate from hydrometric evidence.",
      "No bridge return period or causal probability is inferred from the basin reference.",
    ],
  };
}

export function applyEventReportCuration(context) {
  const additional = ADDITIONAL_CURATIONS[context.event_id];
  if (additional) return applyAdditionalCuration(context, additional);

  const group = findGroup(context.event_id);
  const gap = PIEMONTE_2000_GAPS[context.event_id];
  if (!group && !gap) return null;

  const common = {
    ...context,
    status: "context_available",
    display_badge: "ARPA Piemonte",
    sources: curatedSources(context.sources),
    provenance: {
      method: "Manual extraction encoded in the ARCUS event-report curation registry",
      source_registry_accessed_through: "2026-09-03",
    },
  };
  delete common.review;

  if (gap) {
    const [reasonCode, summaryIt, summaryEn] = gap;
    return {
      ...common,
      coverage_level: "validated_event_report_review",
      event_hydrometry: {
        observation_status: "not_available",
        reason_code: reasonCode,
        observed_discharge_m3s: null,
        observed_stage_m: null,
        hydrograph: null,
        network_status: {
          network: "ARPA Piemonte 13-16 October 2000 event report and controlled event sources",
          summary_it: summaryIt,
          summary_en: summaryEn,
        },
      },
      reference_station: null,
      curation_note: { it: summaryIt, en: summaryEn },
      caveats: [
        "Source review is complete, but no value compatible with the controlled event identity and bridge section is assigned.",
        "A regional flood observation is not transferred across unresolved watercourse or event identities.",
        "The encoded failure process retains its database evidence level and does not prove causation beyond the cited sources.",
        "Rainfall remains separate and is not converted into stage or discharge.",
      ],
    };
  }

  return {
    ...common,
    coverage_level: group.coverage_level,
    event_hydrometry: {
      observation_status: group.observation_status,
      interpretation: group.interpretation,
      observed_discharge_m3s: null,
      observed_stage_m: null,
      hydrograph: null,
      observations: group.observations,
    },
    reference_station: group.station,
    curation_note: { it: group.note_it, en: group.note_en },
    caveats: [
      "The value describes the named official station and is not assigned to the collapsed bridge section.",
      "Reported discharge values retain the reliability class and estimation status published in the event report.",
      "The encoded failure process retains its database evidence level and does not prove causation beyond the cited sources.",
      "No bridge return period or causal probability is inferred from the basin reference.",
    ],
  };
}
